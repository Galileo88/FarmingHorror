"""Write assets/images.js: every PNG under assets/ as a data URL.

Browsers treat each file:// image as cross-origin, which taints the canvas and
stops the game reading sprite pixels. When index.html is opened straight from
disk, the loader takes the images from this file instead.
"""
import base64
import json
import os


def main(assets):
    root = os.path.dirname(assets)
    data = {}
    for folder, _, files in sorted(os.walk(assets)):
        for f in sorted(files):
            if f.endswith('.png'):
                path = os.path.join(folder, f)
                with open(path, 'rb') as fh:
                    data[os.path.relpath(path, root).replace(os.sep, '/')] = 'data:image/png;base64,' + base64.b64encode(fh.read()).decode()
    with open(os.path.join(assets, 'images.js'), 'w') as fh:
        fh.write('// Generated by tools/embed_images.py: the images as data URLs, for running from file://\n')
        fh.write('TA.IMAGE_DATA = ' + json.dumps(data, indent=0) + ';\n')
    print(f'embedded {len(data)} images in assets/images.js')


if __name__ == '__main__':
    main(os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'assets'))
